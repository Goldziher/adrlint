#!/usr/bin/env bash
set -euo pipefail

# update-homebrew-formula.sh <version> <checksums-file>
# Reads the release checksums file (`adrlint_<version>_checksums.txt`) and prints the formula.

if [ $# -ne 2 ]; then
  echo "Usage: $0 <version> <checksums-file>" >&2
  exit 1
fi

VERSION="$1"
SUMS="$2"
BASE="https://github.com/Goldziher/adrlint/releases/download/v${VERSION}"

sha_for() {
  awk -v f="adrlint-$1.tar.gz" '{n=$NF; sub(/^[*]/, "", n); if (n == f) print $1}' "$SUMS"
}

MAC_ARM=$(sha_for aarch64-apple-darwin)
MAC_X64=$(sha_for x86_64-apple-darwin)
LINUX_ARM=$(sha_for aarch64-unknown-linux-gnu)
LINUX_X64=$(sha_for x86_64-unknown-linux-gnu)

for pair in "aarch64-apple-darwin:$MAC_ARM" "x86_64-apple-darwin:$MAC_X64" \
  "aarch64-unknown-linux-gnu:$LINUX_ARM" "x86_64-unknown-linux-gnu:$LINUX_X64"; do
  if [ -z "${pair#*:}" ]; then
    echo "missing checksum for ${pair%%:*} in $SUMS" >&2
    exit 1
  fi
done

cat <<EOF
# typed: false
# frozen_string_literal: true

# Generated by scripts/update-homebrew-formula.sh — do not edit by hand.
class Adrlint < Formula
  desc "Lint and format MADR architecture decision records"
  homepage "https://github.com/Goldziher/adrlint"
  version "${VERSION}"
  license "MIT"

  on_macos do
    on_arm do
      url "${BASE}/adrlint-aarch64-apple-darwin.tar.gz"
      sha256 "${MAC_ARM}"
    end
    on_intel do
      url "${BASE}/adrlint-x86_64-apple-darwin.tar.gz"
      sha256 "${MAC_X64}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/adrlint-aarch64-unknown-linux-gnu.tar.gz"
      sha256 "${LINUX_ARM}"
    end
    on_intel do
      url "${BASE}/adrlint-x86_64-unknown-linux-gnu.tar.gz"
      sha256 "${LINUX_X64}"
    end
  end

  def install
    bin.install "adrlint"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/adrlint --version")
  end
end
EOF
